import { isPeak, priceNow } from '../lib/usage.mjs'
const bj = (s) => Date.parse(s + '+08:00')
const cases = [
  ['2026-10-21T08:59', '周三 08:59'], ['2026-10-21T09:00', '周三 09:00'],
  ['2026-10-21T11:59', '周三 11:59'], ['2026-10-21T12:00', '周三 12:00'],
  ['2026-10-21T13:59', '周三 13:59'], ['2026-10-21T14:00', '周三 14:00'],
  ['2026-10-21T17:59', '周三 17:59'], ['2026-10-21T18:00', '周三 18:00'],
  ['2026-10-24T10:00', '周六 10:00'], ['2026-10-25T15:00', '周日 15:00'],
  ['2026-10-01T10:00', '法定节假日 10:00'],
  ['2026-10-06T15:00', '法定节假日 15:00'],
]
for (const [t, label] of cases) {
  const p = isPeak(bj(t)) ? '峰' : '谷'
  console.log(`${label.padEnd(14)} → ${p}`)
}
